alter table public.tbl_task
  add column if not exists priority public.task_priority not null default 'medium';

create table public.tbl_label (
  label_id integer generated by default as identity primary key,
  user_id uuid not null references public.tbl_user(user_id) on delete cascade,
  name varchar(50) not null,
  color char(7),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tbl_label_name_not_blank check (btrim(name) <> ''),
  constraint tbl_label_user_name_key unique (user_id, name)
);

create table public.tbl_task_label (
  task_id integer not null references public.tbl_task(task_id) on delete cascade,
  label_id integer not null references public.tbl_label(label_id) on delete cascade,
  constraint tbl_task_label_pkey primary key (task_id, label_id)
);

create index tbl_label_user_id_idx on public.tbl_label (user_id);
create index tbl_task_label_label_id_idx on public.tbl_task_label (label_id);

alter table public.tbl_label enable row level security;
alter table public.tbl_task_label enable row level security;

revoke all on public.tbl_label from public, anon, authenticated;
revoke all on public.tbl_task_label from public, anon, authenticated;
revoke all on sequence public.tbl_label_label_id_seq from public, anon, authenticated;
