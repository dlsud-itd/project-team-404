create type public.task_priority as enum ('low', 'medium', 'high');

create table public.tbl_task (
  task_id bigint generated by default as identity primary key,
  user_id uuid not null references public.tbl_user(user_id) on delete cascade,
  project_id integer references public.tbl_project(project_id) on delete set null,
  title varchar(150) not null,
  description varchar(1000),
  priority public.task_priority not null default 'medium',
  due_date date,
  is_done boolean not null default false,
  done_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint tbl_task_title_not_blank check (btrim(title) <> '')
);

create index tbl_task_user_id_idx on public.tbl_task (user_id);
create index tbl_task_project_id_idx on public.tbl_task (project_id);
